// Define u8 as unsigned 8-bit data type (range: 0 to 255)
typedef unsigned char u8;

// Define s8 as signed 8-bit data type (range: -128 to 127)
typedef char s8;

// Define u32 as unsigned 32-bit data type (range: 0 to 4,294,967,295)
typedef unsigned int u32;

// Define s32 as signed 32-bit data type (range: -2,147,483,648 to 2,147,483,647)
typedef int s32;

// Define u16 as unsigned 16-bit data type (range: 0 to 65,535)
typedef unsigned short int u16;

// Define s16 as signed 16-bit data type (range: -32,768 to 32,767)
typedef signed short int s16;

// Define f32 as 32-bit floating-point type (single precision)
typedef float f32;

